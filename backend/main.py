import asyncio
import contextlib
import logging
import os
from collections.abc import AsyncGenerator
from contextlib import asynccontextmanager

from fastapi import FastAPI
from fastapi.responses import JSONResponse

from backend.db.database import check_db, dispose_engine, init_db, session_scope
from backend.routes.brand import router as brand_router
from backend.routes.conversations import router as conversations_router
from backend.routes.copywriter import router as copywriter_router
from backend.routes.qa import router as qa_router
from backend.routes.reviews import router as reviews_router
from backend.services import review_dataset, review_feed
from backend.services.azure_openai import chat_deployment
from backend.services.document_registry import sync_documents
from backend.services.pdf_loader import load_documents
from backend.services.vector_store import initialize_vector_store, split_documents

logging.basicConfig(
    level=os.getenv("LOG_LEVEL", "INFO").upper(),
    format="%(asctime)s %(levelname)s %(name)s: %(message)s",
)
# The HTTP client logs every request at INFO; keep it quiet.
logging.getLogger("httpx").setLevel(logging.WARNING)
logger = logging.getLogger(__name__)


@asynccontextmanager
async def lifespan(app: FastAPI) -> AsyncGenerator[None, None]:
    """Connect to PostgreSQL, build or load the FAISS index, and mirror it to the DB."""
    deployment = chat_deployment()  # raises early if LLM_PROVIDER=azure is misconfigured
    if deployment:
        logger.info("Answers will be generated by Azure OpenAI deployment %s", deployment)
    else:
        logger.info("Azure OpenAI not configured; answers are the top retrieved passage")
    init_db()
    logger.info("Loading policy PDFs for FAISS startup")
    documents = load_documents()
    chunks = split_documents(documents)
    app.state.vector_store = initialize_vector_store(chunks)
    with session_scope() as session:
        sync_documents(session, app.state.vector_store)
        review_dataset.seed(session)  # sample reviews dataset, loaded once
    # Optional simulated live feed of new reviews (REVIEW_FEED_SECONDS).
    interval = review_feed.feed_interval()
    feed = asyncio.create_task(review_feed.run_feed(interval)) if interval else None
    yield
    if feed:
        feed.cancel()
        with contextlib.suppress(asyncio.CancelledError):
            await feed
    dispose_engine()


app = FastAPI(title="MarketMind Marketing Knowledge Assistant API", lifespan=lifespan)
app.include_router(qa_router)
app.include_router(conversations_router)
app.include_router(reviews_router)
app.include_router(brand_router)
app.include_router(copywriter_router)


@app.get("/health")
def health_check() -> JSONResponse:
    database = "ok" if check_db() else "unavailable"
    status = "ok" if database == "ok" else "degraded"
    return JSONResponse(
        {"status": status, "database": database},
        status_code=200 if status == "ok" else 503,
    )
